"""Builds FishDex/Data.lua from Wowhead Classic data cached in .cache/ (zones.json: the
'Fishing' tab of each zone page; recipes.json: the 'Reagent for' tab of each fish page).
Run from the project root: python tools/build_data.py"""
import json

CATS = {
    "fish": [6291, 6303, 6289, 6317, 6361, 21071, 6308, 6522, 6358, 21153, 6359, 8365, 6362,
             4603, 13754, 13758, 13759, 13756, 13755, 13760, 13889, 13893, 13888, 13757, 13422,
             13890, 6299],
    "quest": [6717, 1467, 19975, 16970],
    "trophy": [6292, 6294, 6295, 6309, 6310, 6311, 6363, 6364, 13901, 13902, 13903, 13904,
               13905, 13885, 13886, 13882, 13883, 13884, 13887, 13876, 13907, 13908],
    "wreck": [6356, 6351, 6352, 6353, 6354, 6355, 6357, 6307, 13874, 13875, 13918, 20708,
              21113, 21150],
    "item": [7973, 8366, 13881, 13891, 20709, 21114, 21151, 3820, 7070, 7079, 6297, 6304],
}
PROFESSIONS = {185: "cooking", 171: "alchemy"}
MIN_SHARE = 1.0      # % of a zone's fished items; below it a zone is noise...
MIN_COUNT = 2        # ...unless a rare catch (not a common fish) was seen this often there
MAX_ZONES = 8

zones = json.load(open(".cache/zones.json", encoding="utf-8"))
recipes = json.load(open(".cache/recipes.json", encoding="utf-8"))

seen = {}
for zid, z in zones.items():
    total = sum(i["count"] for i in z["items"])
    if total < 50:
        continue
    for it in z["items"]:
        share = it["count"] / total * 100
        seen.setdefault(it["id"], {"name": it["name"], "zones": []})
        seen[it["id"]]["zones"].append((share, it["count"], int(zid)))

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["-- GENERATED by tools/build_data.py from Wowhead Classic (zone 'Fishing' tabs and",
       "-- item 'Reagent for' tabs). Do not edit by hand: change the script and rebuild.",
       "-- names are English fallbacks; the game's own localized names are shown when it has them.",
       "local _, ns = ...", "", "local Data = {}", "ns.Data = Data", "",
       'Data.CATEGORIES = { "fish", "quest", "trophy", "wreck", "item" }', "",
       "-- AreaTable zone id -> English name (C_Map.GetAreaInfo gives the localized one).",
       "Data.ZONES = {"]
used_zones = set()
items = []
for cat, ids in CATS.items():
    for iid in ids:
        info = seen.get(iid)
        if not info:
            raise SystemExit("no Wowhead fishing data for item %d" % iid)
        kept = [(sh, z) for sh, n, z in info["zones"]
                if sh >= MIN_SHARE or (cat != "fish" and n >= MIN_COUNT)]
        zs = [z for _, z in sorted(kept, reverse=True)[:MAX_ZONES]]
        used_zones.update(zs)
        recs = []
        for r in recipes.get(str(iid), []):
            skill = (r.get("skill") or [None])[0]
            if skill in PROFESSIONS and r["id"] < 400000 and not r["name"].startswith("Copy of"):
                recs.append((r["id"], PROFESSIONS[skill], r.get("lvl") or 0, r["name"]))
        items.append((cat, iid, info["name"], zs, recs))
for zid in sorted(used_zones):
    out.append("    [%d] = %s," % (zid, lua_str(zones[str(zid)]["name"])))
out += ["}", "",
        "-- Spell id -> { profession, required skill, English name }.",
        "Data.RECIPES = {"]
allrec = {}
for _, _, _, _, recs in items:
    for sid, prof, lvl, name in recs:
        allrec[sid] = (prof, lvl, name)
for sid in sorted(allrec):
    prof, lvl, name = allrec[sid]
    out.append('    [%d] = { "%s", %d, %s },' % (sid, prof, lvl, lua_str(name)))
out += ["}", "",
        "-- Ordered entries: item id, category, English name, zones (most fished first), recipes.",
        "Data.ENTRIES = {"]
for cat, iid, name, zs, recs in items:
    out.append('    { id = %d, cat = "%s", name = %s, zones = { %s }, recipes = { %s } },' % (
        iid, cat, lua_str(name), ", ".join(map(str, zs)), ", ".join(str(r[0]) for r in recs)))
out += ["}", ""]
open("FishDex/Data.lua", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("entries", len(items), "zones", len(used_zones), "recipes", len(allrec))
